func write(t *testing.T, dir, rel, content string) {
	t.Helper()
	p := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func git(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v: %s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

// newRepo returns an initialized repository with no commits.
func newRepo(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	dir := t.TempDir()
	git(t, dir, "init", "-q", "-b", "main")
	git(t, dir, "config", "user.email", "warden@test.local")
	git(t, dir, "config", "user.name", "Warden Test")
	git(t, dir, "config", "commit.gpgsign", "false")
	return dir
}

// commit stages exactly the named paths and commits them, returning HEAD.
func commit(t *testing.T, dir string, paths ...string) string {
	t.Helper()
	git(t, dir, append([]string{"add", "--"}, paths...)...)
	git(t, dir, "commit", "-q", "-m", "c")
	return git(t, dir, "rev-parse", "HEAD")
}

func sha256Hex(s string) string {
	sum := sha256.Sum256([]byte(s))
	return "sha256:" + hex.EncodeToString(sum[:])
}

func TestCollect_FindsLockfilesDigestedAndSorted(t *testing.T) {
	dir := newRepo(t)
	write(t, dir, "go.sum", "example.com/x v1.0.0 h1:abc=\n")
	write(t, dir, "web/package-lock.json", `{"name":"x"}`)
	write(t, dir, "src/main.go", "package main") // not a lockfile
	head := commit(t, dir, "go.sum", "web/package-lock.json", "src/main.go")

	got := New().Collect(dir, head)
	if len(got) != 2 {
		t.Fatalf("expected 2 lockfiles, got %d: %+v", len(got), got)
	}
	// Sorted by path: go.sum before web/package-lock.json.
	if got[0].Path != "go.sum" || got[1].Path != "web/package-lock.json" {
		t.Errorf("not sorted by path: %+v", got)
	}
	if got[0].Ecosystem != "go" || got[1].Ecosystem != "npm" {
		t.Errorf("ecosystems wrong: %+v", got)
	}
	if got[0].Digest != sha256Hex("example.com/x v1.0.0 h1:abc=\n") {
		t.Errorf("digest = %q, want the sha256 of the committed content", got[0].Digest)
	}
}

func TestCollect_DigestChangesWithContent(t *testing.T) {
	dir := newRepo(t)
	write(t, dir, "Cargo.lock", "v1")
	c1 := commit(t, dir, "Cargo.lock")
	write(t, dir, "Cargo.lock", "v2")
	c2 := commit(t, dir, "Cargo.lock")
	if New().Collect(dir, c1)[0].Digest == New().Collect(dir, c2)[0].Digest {
		t.Error("digest must change when the committed lockfile changes")
	}
}

func TestCollect_NoLockfilesIsEmpty(t *testing.T) {
	dir := newRepo(t)
	write(t, dir, "README.md", "hi")
	head := commit(t, dir, "README.md")
	if got := New().Collect(dir, head); len(got) != 0 {
		t.Errorf("expected empty SBOM, got %+v", got)
	}
}

// The SBOM rides inside a signed note that attests a commit, so it must state
// only what that commit contains. Walking the filesystem claimed whatever a
// step left behind: an untracked lockfile a build generated, or a tracked one
// a step rewrote without committing. Both are facts about the worktree, not
// about the commit.
func TestCollect_ReadsTheCommittedTreeNotTheWorktree(t *testing.T) {
	dir := newRepo(t)
	const committed = "{\"lockfileVersion\":3}\n"
	write(t, dir, "package-lock.json", committed)
	write(t, dir, "src/app.go", "package app")
	head := commit(t, dir, "package-lock.json", "src/app.go")

	// A step generated a lockfile nobody committed, and modified the tracked one.
	write(t, dir, "Cargo.lock", "# generated by a step\n")
	write(t, dir, "web/yarn.lock", "# also generated\n")
	write(t, dir, "package-lock.json", "{\"lockfileVersion\":3,\"tampered\":true}\n")

	got := New().Collect(dir, head)
	want := []domain.DependencyManifest{{Ecosystem: "npm", Path: "package-lock.json", Digest: sha256Hex(committed)}}
	if len(got) != len(want) || got[0] != want[0] {
		t.Fatalf("Collect = %+v, want %+v (untracked lockfiles must not be listed; content must be the committed blob)", got, want)
	}
}

// A lockfile that is a symlink in the tree, or a submodule entry, has no
// committed content to digest; neither may be claimed.
func TestCollect_SkipsSymlinksAndSubmodules(t *testing.T) {
	dir := newRepo(t)
	write(t, dir, "real.lock", "x")
	if err := os.Symlink("real.lock", filepath.Join(dir, "go.sum")); err != nil {
		t.Skip("symlinks unavailable:", err)
	}
	head := commit(t, dir, "real.lock", "go.sum")
	if got := New().Collect(dir, head); len(got) != 0 {
		t.Errorf("a symlinked lockfile must not be claimed, got %+v", got)
	}
}

func TestCollect_UnresolvableRevIsEmpty(t *testing.T) {
	dir := newRepo(t)
	write(t, dir, "go.sum", "x")
	_ = commit(t, dir, "go.sum")
	for _, rev := range []string{"", "0000000000000000000000000000000000000000", "no-such-ref"} {
		if got := New().Collect(dir, rev); len(got) != 0 {
			t.Errorf("Collect(%q) = %+v, want empty", rev, got)
		}
	}
	if got := New().Collect(t.TempDir(), "HEAD"); len(got) != 0 {
		t.Errorf("Collect outside a repository = %+v, want empty", got)
	}
}
